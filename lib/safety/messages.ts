/**
 * 三级处置话术模板（safety-protocol.md §5）
 *
 * 话术不是定稿（协议声明：实际文案以 UI 为准），以下为骨架级默认文案：
 * - 硬拦截（§5.1）：固定话术、不解释判定依据、不与被拒内容继续对话——由客户端词表命中触发，消息不发送；
 * - 软引导（§5.2）：由普通聊天的基础 system prompt 承载（模型按历史自行把握「第一次引导/第二次结束」，
 *   见 lib/safety/prompts.ts）；
 * - 关怀转介（§5.3）：行为锁定——表达关切 + 专业渠道 + 一句能力说明后结束，
 *   **不做诊断式追问、不推测原因、不提供心理建议**（本协议风险最高的一类）。
 *   客户端词表命中 psych 类触发，消息不发送。
 */

/** 处置级别：hard 硬拦截 / psych 关怀转介（soft 软引导由模型侧承载，不走此通道） */
export type SafetyLevel = 'hard' | 'psych';

/**
 * 系统自身拒答的固定前缀（机器可读，唯一来源）。
 *
 * 为什么需要它：上游拦截判定（lib/safety/block-detect.ts）靠「流中出现拒绝性文本」兜底，
 * 而系统自己的边界拒答（非学科请求、索取系统提示、要求无限制模式）同样是拒绝性文本，
 * 两者形态上无法区分——不加标记就会把自家合规拒答误判成上游拦截，前端弹出
 * 「内容被服务商拒绝」的错误话术，且本轮历史被丢弃。
 *
 * 约定：凡按边界条款拒答，正文第一行以该前缀开头（由诊断提示词 DISCIPLINE_BLOCK /
 * 普通聊天 system prompt 要求模型输出）；isBlockedSignal 对该前缀豁免，但
 * finish_reason 异常值不豁免（那是上游行为，优先级高于文本形态）。
 */
export const REFUSAL_PREFIX = '【边界说明】';

